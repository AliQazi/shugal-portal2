import Register from "../models/Register.js";
import SubUserRole from "../models/SubUserRole.js";
import { ROLE_PERMISSIONS, getPermissionKeysForRole } from "../utils/permissions.js";
import { sendAdminCredentialsEmail } from "../utils/emailService.js";
import crypto from "crypto";
import ActivityLog from "../models/activitylogs.js";

const isSuperAdminUser = (user) => user?.userRole === "Super Admin" || user?.role === "Super Admin";
const getOwnerAdminId = (user) => (user?.isSubUser ? user.parentAdminId || user._id : user?._id);

const getSubUserQuery = (req, id) => ({
  ...(id ? { _id: id } : {}),
  isSubUser: true,
  ...(isSuperAdminUser(req.user) ? {} : { parentAdminId: getOwnerAdminId(req.user) }),
});

const normalizePermissions = (permissions) => [...new Set(permissions)];

/**
 * Create a new sub-user
 */
export const createSubUser = async (req, res) => {
  try {
    const ownerAdminId = getOwnerAdminId(req.user);
    const { name, email, phone, userRole, permissions, companyName, address, city, country } = req.body;

    // Validate input
    if (!name || !email || !phone) {
      return res.status(400).json({
        message: "Name, email, and phone are required",
      });
    }

    if (!Array.isArray(permissions) || permissions.length === 0) {
      return res.status(400).json({
        message: "At least one permission is required",
      });
    }

    // Check if email already exists
    const existingUser = await Register.findOne({ email });
    if (existingUser) {
      return res.status(400).json({
        message: "Email already registered",
      });
    }

    // Generate temporary password
    const tempPassword = crypto.randomBytes(8).toString("hex");

    const subUserPermissions = normalizePermissions(permissions);

    // Create sub-user
    const subUser = new Register({
      name,
      email,
      phone,
      password: tempPassword,
      plainPassword: tempPassword,
      isAutoGeneratedPassword: true,
      role: "Admin", // Keep role as Admin for backward compatibility
      userRole: userRole || "Admin",
      companyName: companyName || name,
      address: address || "",
      city: city || "",
      country: country || "",
      status: "Pending",
      parentAdminId: ownerAdminId,
      createdBy: req.user._id,
      isSubUser: true,
      permissions: subUserPermissions,
    });

    await subUser.save();

    // Populate ownership and creator info
    await subUser.populate([
      { path: "parentAdminId", select: "name email" },
      { path: "createdBy", select: "name email" },
    ]);

    // Return sub-user data (without password)
    await ActivityLog.create({
      user: req.user._id,
      type: "Sub User",
      refModel: "Register",
      refId: subUser._id,
      description: `Sub-user "${subUser.name}" (${subUser.userRole}) created`,
    });

    res.status(201).json({
      message: "Sub-user created successfully",
      data: {
        _id: subUser._id,
        name: subUser.name,
        email: subUser.email,
        phone: subUser.phone,
        userRole: subUser.userRole,
        permissions: subUser.permissions,
        status: subUser.status,
        companyName: subUser.companyName,
        address: subUser.address,
        city: subUser.city,
        country: subUser.country,
        parentAdmin: subUser.parentAdminId,
        createdBy: subUser.createdBy,
        tempPassword, // Only shown once during creation
      },
    });
  } catch (error) {
    console.error("Error creating sub-user:", error);
    res.status(500).json({
      message: "Error creating sub-user",
      error: error.message,
    });
  }
};

/**
 * Get all sub-users for the authenticated admin
 */
export const getSubUsers = async (req, res) => {
  try {
    const query = getSubUserQuery(req);

    const subUsers = await Register.find(query)
      .populate("createdBy", "name email")
      .populate("parentAdminId", "name email")
      .sort({ createdAt: -1 });

    res.status(200).json({
      message: "Sub-users retrieved successfully",
      count: subUsers.length,
      data: subUsers,
    });
  } catch (error) {
    console.error("Error fetching sub-users:", error);
    res.status(500).json({
      message: "Error fetching sub-users",
      error: error.message,
    });
  }
};

/**
 * Get a specific sub-user by ID
 */
export const getSubUserById = async (req, res) => {
  try {
    const { id } = req.params;
    const subUser = await Register.findOne(getSubUserQuery(req, id))
      .select("-password -plainPassword")
      .populate("createdBy", "name email")
      .populate("parentAdminId", "name email");

    if (!subUser) {
      return res.status(404).json({
        message: "Sub-user not found",
      });
    }

    res.status(200).json({
      message: "Sub-user retrieved successfully",
      data: subUser,
    });
  } catch (error) {
    console.error("Error fetching sub-user:", error);
    res.status(500).json({
      message: "Error fetching sub-user",
      error: error.message,
    });
  }
};

/**
 * Update a sub-user
 */
export const updateSubUser = async (req, res) => {
  try {
    const { id } = req.params;
    const { name, phone, userRole, permissions, status, companyName, address, city, country } = req.body;

    // Find sub-user
    const subUser = await Register.findOne(getSubUserQuery(req, id));

    if (!subUser) {
      return res.status(404).json({
        message: "Sub-user not found",
      });
    }

    // Update fields
    if (name) subUser.name = name;
    if (phone) subUser.phone = phone;
    if (userRole) {
      subUser.userRole = userRole;
      // Update permissions based on role
      subUser.permissions = normalizePermissions(getPermissionKeysForRole(userRole));
    }
    if (Array.isArray(permissions)) {
      subUser.permissions = normalizePermissions(permissions);
    }
    if (status) subUser.status = status;
    if (companyName) subUser.companyName = companyName;
    if (address !== undefined) subUser.address = address;
    if (city !== undefined) subUser.city = city;
    if (country !== undefined) subUser.country = country;

    await subUser.save();

    await ActivityLog.create({
      user: req.user._id,
      type: "Sub User",
      refModel: "Register",
      refId: subUser._id,
      description: `Sub-user "${subUser.name}" updated`,
    });

    res.status(200).json({
      message: "Sub-user updated successfully",
      data: subUser,
    });
  } catch (error) {
    console.error("Error updating sub-user:", error);
    res.status(500).json({
      message: "Error updating sub-user",
      error: error.message,
    });
  }
};

