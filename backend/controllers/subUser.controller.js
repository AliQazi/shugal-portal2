/**
 * Send sub-user admin portal credentials by email
 */
export const sendSubUserCredentials = async (req, res) => {
  try {
    const { id } = req.params;
    const subUser = await Register.findOne(getSubUserQuery(req, id));

    if (!subUser) {
      return res.status(404).json({
        success: false,
        message: "Sub-user not found",
      });
    }

    if (!subUser.email || !subUser.plainPassword) {
      return res.status(400).json({
        success: false,
        message: "Missing required credentials. Ensure email and password are available.",
      });
    }

    await sendAdminCredentialsEmail(
      subUser.email,
      subUser.plainPassword,
      subUser.name,
      subUser.companyName || "N/A",
    );

    res.status(200).json({
      success: true,
      message: `Credentials have been sent successfully to ${subUser.email}`,
    });
  } catch (error) {
    console.error("Error sending sub-user credentials:", error);
    res.status(500).json({
      success: false,
      message: "Failed to send credentials email. Please check email configuration.",
    });
  }
};
